"""`mf docs render [--check]` — generate the docs that mirror the code (M11, ТЗ §2.3, §8.2).

Phases, modes, events and the degradation table are defined once, in Python (M11); the markdown
views under `docs/` are generated from those modules and `--check` fails when a file on disk has
drifted from its source of truth. `docs/permissions.md` is the README block of §8.2 and is built from
`hooks/allowlist.txt` — that file arrives with wave W2, so until then the target is skipped with a
note instead of inventing hosts.
"""

